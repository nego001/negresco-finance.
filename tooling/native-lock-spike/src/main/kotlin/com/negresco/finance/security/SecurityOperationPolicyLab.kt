package com.negresco.finance.security

/**
 * Pure, offline risk preflight for the proposed Negresco Security Engine.
 *
 * A positive result is NEVER a cryptographic authorization, a capability,
 * a bypass for Keystore, or permission to access the user's financial data.
 * The future native authorizer must recheck the current persisted revision,
 * lifecycle, session, and a fresh CryptoObject-backed operation.
 *
 * This laboratory is NOT bundled with Expo or exposed to JavaScript.
 */
internal enum class ProtectedOperation {
  VIEW_FINANCIAL_OVERVIEW,
  REVEAL_SENSITIVE_RECORD,
  EXPORT_FINANCIAL_DATA,
  REGISTER_NEW_DEVICE,
  REVOKE_DEVICE,
  CHANGE_RECOVERY_MATERIAL,
  CHANGE_TRUSTED_ENVIRONMENT,
  DISABLE_MAXIMUM_PROTECTION,
  DISABLE_BIOMETRIC_LOCK,
  RESTORE_ENCRYPTED_BACKUP,
  DELETE_ENCRYPTION_KEYS
}

internal enum class PreflightVerdict {
  DENY,
  REQUIRE_FRESH_STRONG_AUTH,
  PROCEED_TO_INDEPENDENT_NATIVE_AUTHORIZER
}

internal enum class PreflightReason {
  EMERGENCY_LOCK,
  UNSUPPORTED_DESTRUCTIVE_OPERATION,
  NOT_FOREGROUND,
  NO_VERIFIED_SESSION,
  STORAGE_NOT_VERIFIED,
  DEVICE_NOT_TRUSTED,
  UNTRUSTED_OVERLAY,
  SCREEN_PRIVACY_UNAVAILABLE,
  SECURITY_TELEMETRY_MISSING,
  HIGH_RISK_CONTEXT,
  NETWORK_NOT_TRUSTED_FOR_DEVICE_REGISTRATION,
  REAUTH_REQUIRED,
  READY_FOR_NATIVE_VERIFICATION
}

internal data class SecuritySignals(
  val inForeground: Boolean,
  val sessionVerified: Boolean,
  val storageVerified: Boolean,
  val trustedDevice: Boolean,
  val screenCaptureProtected: Boolean,
  val overlaySuspected: Boolean,
  val networkTrusted: Boolean,
  val riskTelemetryAvailable: Boolean,
  val suspiciousActivity: Boolean,
  val freshStrongAuthentication: Boolean,
  val emergencyLock: Boolean,
  val maximumProtection: Boolean
)

internal data class PreflightDecision(
  val verdict: PreflightVerdict,
  val reason: PreflightReason
)

/**
 * No network or filesystem calls, no key material and no persistent grants.
 * Inputs MUST be generated by native, authenticated detectors, never JS/AI.
 * Any unverified essential fact maps to false in the caller and fails closed.
 */
internal object SecurityOperationPolicyLab {
  private fun deny(reason: PreflightReason) =
    PreflightDecision(PreflightVerdict.DENY, reason)
  private fun stepUp(reason: PreflightReason) =
    PreflightDecision(PreflightVerdict.REQUIRE_FRESH_STRONG_AUTH, reason)

  fun evaluate(action: ProtectedOperation, s: SecuritySignals): PreflightDecision {
    // Emergency lockdown cannot be bypassed with biometrics from an old session.
    if (s.emergencyLock) return deny(PreflightReason.EMERGENCY_LOCK)

    // Recovery must use a separately audited protocol; disabling encryption
    // and a biometric lock cannot be added via a "mode" toggle.
    if (action == ProtectedOperation.DISABLE_BIOMETRIC_LOCK ||
        action == ProtectedOperation.DELETE_ENCRYPTION_KEYS ||
        action == ProtectedOperation.RESTORE_ENCRYPTED_BACKUP) {
      return deny(PreflightReason.UNSUPPORTED_DESTRUCTIVE_OPERATION)
    }
    if (!s.inForeground) return deny(PreflightReason.NOT_FOREGROUND)
    if (!s.sessionVerified) return deny(PreflightReason.NO_VERIFIED_SESSION)
    if (!s.storageVerified) return deny(PreflightReason.STORAGE_NOT_VERIFIED)
    if (!s.trustedDevice) return deny(PreflightReason.DEVICE_NOT_TRUSTED)
    if (s.overlaySuspected) return deny(PreflightReason.UNTRUSTED_OVERLAY)

    val privacySensitive =
      action == ProtectedOperation.REVEAL_SENSITIVE_RECORD ||
      action == ProtectedOperation.EXPORT_FINANCIAL_DATA ||
      action == ProtectedOperation.CHANGE_RECOVERY_MATERIAL
    if (privacySensitive && !s.screenCaptureProtected) {
      return deny(PreflightReason.SCREEN_PRIVACY_UNAVAILABLE)
    }

    val critical = action != ProtectedOperation.VIEW_FINANCIAL_OVERVIEW

    // Missing fraud telemetry is NOT interpreted as "low risk". For critical
    // operations fail closed; readings can still be gated by strong auth.
    if (!s.riskTelemetryAvailable && critical) {
      return deny(PreflightReason.SECURITY_TELEMETRY_MISSING)
    }
    if (s.suspiciousActivity && critical) {
      return deny(PreflightReason.HIGH_RISK_CONTEXT)
    }

    // Registering an unknown device on an unknown network is forbidden;
    // trusted Wi-Fi by itself is never an authorization.
    if (action == ProtectedOperation.REGISTER_NEW_DEVICE && !s.networkTrusted) {
      return deny(PreflightReason.NETWORK_NOT_TRUSTED_FOR_DEVICE_REGISTRATION)
    }

    // Maximum mode steps up dashboard reads on unknown networks or anomalies.
    val maximumContextRequiresStepUp = s.maximumProtection &&
      (!s.networkTrusted || !s.riskTelemetryAvailable || s.suspiciousActivity)
    if ((critical || maximumContextRequiresStepUp) && !s.freshStrongAuthentication) {
      return stepUp(PreflightReason.REAUTH_REQUIRED)
    }

    return PreflightDecision(
      PreflightVerdict.PROCEED_TO_INDEPENDENT_NATIVE_AUTHORIZER,
      PreflightReason.READY_FOR_NATIVE_VERIFICATION
    )
  }
}
