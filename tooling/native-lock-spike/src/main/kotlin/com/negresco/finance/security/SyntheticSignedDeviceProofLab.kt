package com.negresco.finance.security

import java.io.ByteArrayOutputStream
import java.io.DataOutputStream
import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.security.PublicKey
import java.security.Signature
import java.security.interfaces.EdECPublicKey

/**
 * SEC-05: real Ed25519 SIGNATURE VERIFICATION over a synthetic device claim.
 *
 * Still strictly JVM-LAB. The trust anchor/public key registration, random
 * challenge issuance, account binding, durable counter persistence, expiry,
 * device attestation, hardware-private-key custody, and server anti-rollback
 * are NOT provided. A verified signature is not permission to access funds.
 *
 * No private keys are accepted, produced, stored, logged or exported here.
 */
internal object SyntheticSignedDeviceProofLab {
  private val domain = "negresco.finance.device-proof.ed25519.v1"
    .toByteArray(StandardCharsets.US_ASCII)
  private const val NONCE_LENGTH = 32
  private const val SIGNATURE_LENGTH = 64

  /** Explicit stable wire identifiers. Never use enum ordinals. */
  private fun wireCode(operation: ProtectedOperation): Int = when (operation) {
    ProtectedOperation.VIEW_FINANCIAL_OVERVIEW -> 1
    ProtectedOperation.REVEAL_SENSITIVE_RECORD -> 2
    ProtectedOperation.EXPORT_FINANCIAL_DATA -> 3
    ProtectedOperation.REGISTER_NEW_DEVICE -> 4
    ProtectedOperation.REVOKE_DEVICE -> 5
    ProtectedOperation.CHANGE_RECOVERY_MATERIAL -> 6
    ProtectedOperation.CHANGE_TRUSTED_ENVIRONMENT -> 7
    ProtectedOperation.DISABLE_MAXIMUM_PROTECTION -> 8
    ProtectedOperation.DISABLE_BIOMETRIC_LOCK -> 9
    ProtectedOperation.RESTORE_ENCRYPTED_BACKUP -> 10
    ProtectedOperation.DELETE_ENCRYPTION_KEYS -> 11
  }

  /**
   * The future enrollment protocol must authenticate ownership of this
   * EXACT public key, not simply accept a client-supplied key in a request.
   */
  fun fingerprint(publicKey: PublicKey): DeviceKeyFingerprint? {
    if (!isEd25519(publicKey)) return null
    val bytes = publicKey.encoded ?: return null
    if (bytes.isEmpty() || bytes.size > 128) return null
    val hash = MessageDigest.getInstance("SHA-256").digest(bytes)
    val hex = hash.joinToString("") { "%02x".format(it.toInt() and 0xff) }
    return DeviceKeyFingerprint.parse(hex)
  }

  private fun isEd25519(publicKey: PublicKey): Boolean =
    publicKey is EdECPublicKey && publicKey.params.name == "Ed25519" &&
      publicKey.format == "X.509"

  /**
   * Canonical, unambiguous challenge encoding. nonce MUST be independently
   * generated by a trusted issuer, tied to a single account+installation,
   * stored as outstanding, expired and marked consumed in durable storage.
   * THIS LAB ONLY tests serialization, it does not implement an issuer.
   */
  fun canonicalPayload(claim: PresentedDeviceOperation, nonce: ByteArray): ByteArray {
    require(nonce.size == NONCE_LENGTH)
    require(claim.registryRevision >= 1L && claim.epoch >= 1L &&
      claim.epoch <= claim.registryRevision &&
      claim.sequence in 1L until Long.MAX_VALUE)
    val fingerprint = claim.fingerprint.hex
      .chunked(2).map { it.toInt(16).toByte() }.toByteArray()
    require(fingerprint.size == 32)
    return ByteArrayOutputStream().also { buffer ->
      DataOutputStream(buffer).use { stream ->
        stream.writeInt(domain.size)
        stream.write(domain)
        stream.writeInt(1) // schema version
        stream.writeInt(fingerprint.size)
        stream.write(fingerprint)
        stream.writeLong(claim.registryRevision)
        stream.writeLong(claim.epoch)
        stream.writeLong(claim.sequence)
        stream.writeInt(wireCode(claim.operation))
        stream.writeInt(nonce.size)
        stream.write(nonce)
      }
    }.toByteArray()
  }

  /** Fail-closed: no arbitrary strings, identity claims, or signed booleans. */
  fun verify(
    claim: PresentedDeviceOperation,
    enrolledPublicKey: PublicKey?,
    independentlyIssuedNonce: ByteArray?,
    presentedNonce: ByteArray?,
    signature: ByteArray?
  ): Boolean {
    if (enrolledPublicKey == null || !isEd25519(enrolledPublicKey) ||
      independentlyIssuedNonce == null || independentlyIssuedNonce.size != NONCE_LENGTH ||
      presentedNonce == null || presentedNonce.size != NONCE_LENGTH ||
      signature == null || signature.size != SIGNATURE_LENGTH ||
      !MessageDigest.isEqual(independentlyIssuedNonce, presentedNonce)) return false
    return try {
      if (fingerprint(enrolledPublicKey) != claim.fingerprint) return false
      val payload = canonicalPayload(claim, presentedNonce.copyOf())
      val verifier = Signature.getInstance("Ed25519")
      verifier.initVerify(enrolledPublicKey)
      verifier.update(payload)
      verifier.verify(signature.copyOf())
    } catch (_: Exception) {
      false
    }
  }
}
